            c, fr, ...
            S.nuc_volume_mesh(c, fr), S.nuc_volume_from_seg(c, fr), ...
            S.nuc_mesh_sphericity(c, fr), S.nuc_height(c, fr), ...
            S.nuc_same_vol_sphere_rad(c, fr), ...
            S.nuc_mesh_z_min(c, fr), S.nuc_mesh_z_max(c, fr));
    end
end
fclose(fid);
fprintf('WROTE %s  (%d rows, %d non-NaN volumes)\n', out, ncell*nframe, ...
        sum(~isnan(S.nuc_volume_mesh(:))));
fprintf('DONE\n');
